const today = new Date();

console.log("Current Date:", today);

console.log("Year:", today.getFullYear());

console.log("Month:", today.getMonth() + 1);

console.log("Day:", today.getDate());

console.log("Day:", today.getDay()); // **Note:** We haven't learned `getDay()` yet. It returns the day of the week (0 = Sunday, 1 = Monday, etc.). We'll cover it in a future lesson.

console.log("Hour:", today.getHours());

console.log("Minute:", today.getMinutes());

console.log("Second:", today.getSeconds());

